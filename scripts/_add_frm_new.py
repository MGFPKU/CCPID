def _load_rows(path: Path) -> list[list[str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.reader(handle))


def _write_rows(path: Path, rows: list[list[str]]):
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerows(rows)


def _approach_code(pid: str) -> str:
    """Extract approach code from PID: CHNFRM{CODE}I{seq}S{seq} -> CODE."""
    return pid[6:9]


def main():
    existing = _load_rows(CSV_PATH)
    header, data = existing[0], existing[1:]

    # Sort new rows by approach code for alphabetical insertion
    ROWS.sort(key=lambda r: _approach_code(r[0]))

    inserted = 0
    for row in ROWS:
        pid = row[0]
        if any(r[0] == pid for r in data):
            print(f"  {pid} already in CSV — skipping")
            continue

        new_code = _approach_code(pid)

        # Find the correct insertion position: after the last existing FRM row
        # whose approach code < new_code. If same code exists, insert after the
        # last row with that code.
        insert_pos = None
        for i, r in enumerate(data):
            if r[2] != "框架性规制":
                continue
            existing_code = _approach_code(r[0])
            if existing_code <= new_code:
                insert_pos = i + 1  # insert after this row

        if insert_pos is None:
            # New approach comes before all existing — insert before first FRM row
            for i, r in enumerate(data):
                if r[2] == "框架性规制":
                    insert_pos = i
                    break

        if insert_pos is None:
            print("ERROR: No Framework regulation section found")
            return 1

        data.insert(insert_pos, list(row))
        inserted += 1
        print(f"  Inserted {pid} ({new_code}) at data index {insert_pos}")

    _write_rows(CSV_PATH, [header] + data)
    print(f"Wrote {CSV_PATH} ({len(data)} data rows, {inserted} inserted)")


