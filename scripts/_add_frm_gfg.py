def _load_rows(path: Path) -> list[list[str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.reader(handle))


def _write_rows(path: Path, rows: list[list[str]]):
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerows(rows)


def main():
    existing = _load_rows(CSV_PATH)
    header, data = existing[0], existing[1:]

    # Check if already present
    if any(r[0] == PID for r in data):
        print(f"  {PID} already in CSV — skipping")
        return 0

    row = make_row()

    # Insert after the last EPR row (GFG > EPR alphabetically, GFG < ITG)
    insert_pos = None
    for i in range(len(data) - 1, -1, -1):
        if data[i][2] == "框架性规制" and data[i][0][6:9] == "EPR":
            insert_pos = i + 1
            break

    if insert_pos is None:
        # Fallback: insert after PDP (closest preceding code before GFG in FRM block)
        for i in range(len(data) - 1, -1, -1):
            if data[i][2] == "框架性规制" and data[i][0][6:9] in ("EPR", "EPM", "EEM", "EEZ", "ECO", "ECM"):
                insert_pos = i + 1
                break

    if insert_pos is None:
        print("ERROR: No Framework regulation section found")
        return 1

    data.insert(insert_pos, row)
    _write_rows(CSV_PATH, [header] + data)
    print(f"  Inserted {PID} at data index {insert_pos}")
    print(f"Wrote {CSV_PATH} ({len(data)} data rows)")


if __name__ == "__main__":
    raise SystemExit(main())
