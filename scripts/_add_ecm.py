def main():
    for row in [ECM01, ECM02, ECM03]:
        if len(row) != 53:
            print(f"ERROR: {row[0]} has {len(row)} columns, expected 53")
            return 1

    path = CSV_PATH
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.reader(f)
        header = next(reader)
        existing = list(reader)

    # Find where to insert: after PSM01 (last PSM), before RPD01 (first RPD)
    insert_at = len(existing)
    for i, r in enumerate(existing):
        if r[0].startswith("CHNFRMRPD"):
            insert_at = i
            break

    print(f"Inserting ECM01–ECM03 at row index {insert_at} (before first RPD)")
    for j, row in enumerate(reversed([ECM01, ECM02, ECM03])):
        existing.insert(insert_at, row)
        print(f"  {row[0]} inserted")

    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(existing)

    print("ECM01–ECM03 added to CN regulatory instruments CSV.")
    return 0


