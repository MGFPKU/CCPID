#!/usr/bin/env python3
"""Insert 3 cooking MEPS instruments into CN regulatory CSV."""
import csv
from pathlib import Path

CN_CSV = Path("D:/CCPID-cc/outputs/CCPID_cn_regulatory_instruments.csv")

# Read existing rows
with CN_CSV.open("r", encoding="utf-8-sig", newline="") as f:
    reader = csv.reader(f)
    rows = list(reader)

header = rows[0]
# Find insertion point: after last PRF instrument (CHNPRFMEBI02S000), before CHNFRMEPMI01S000
insert_at = None
for i, row in enumerate(rows):
    if i == 0:
        continue
    if row[0].startswith("CHNFRMEPMI01"):
        insert_at = i
        break

if insert_at is None:
    raise SystemExit("Could not find CHNFRMEPMI01S000 in CSV")

# Build 3 new rows (same column order as header)
def make_row(**kwargs):
    """Build a CSV row from keyword args, filling missing with '' or 'N/A'."""
    result = []
    for col in header:
        if col in kwargs:
            result.append(kwargs[col])
        elif col == "政策包":
            result.append("N/A")
        elif col in ("终止日期", "管辖地名称"):
            result.append("N/A")
        elif col in ("受规制资产（其他）", "合规计算方法I", "合规计算方法II"):
            result.append("N/A")
        elif col in ("强度（数值）", "强度（单位）", "强度（详情）"):
            # Cooking MEPS have intensity data
            if col in kwargs:
                result.append(kwargs[col])
            else:
                result.append("N/A")
        else:
            result.append("N/A")
    return result

