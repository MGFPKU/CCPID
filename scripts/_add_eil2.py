def main():
    instruments = [
        EIL11, EIL12, EIL13, EIL14, EIL15,
        EIL16, EIL17, EIL18, EIL19, EIL20,
    ]

    # Read existing CSV
    if CSV_PATH.exists():
        with CSV_PATH.open("r", encoding="utf-8-sig", newline="") as f:
            reader = csv.DictReader(f)
            cols = reader.fieldnames
            existing_rows = list(reader)
    else:
        print(f"ERROR: {CSV_PATH} not found")
        sys.exit(1)

    # Check for duplicate IDs
    existing_ids = {r[cols[0]] for r in existing_rows}
    new_instruments = [i for i in instruments if i["政策工具ID"] not in existing_ids]
    for inst in instruments:
        if inst["政策工具ID"] in existing_ids:
            print(f"  SKIP: {inst['政策工具ID']} already exists — use fill_instrument.py add --force to update")

    if not new_instruments:
        print("All instruments already exist. Nothing to do.")
        return

    # Insert after the last performance-standard instrument
    insert_idx = 0
    last_ps = -1
    for i, row in enumerate(existing_rows):
        if row["组别"] == "绩效标准":
            last_ps = i
        if row["组别"] != "绩效标准" and last_ps >= 0:
            break
    insert_idx = last_ps + 1

    for inst in new_instruments:
        existing_rows.insert(insert_idx, inst)
        insert_idx += 1
        print(f"  ADD: {inst['政策工具ID']} — {inst['本国工具名称']}")

    with CSV_PATH.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=cols)
        writer.writeheader()
        writer.writerows(existing_rows)

    print(f"\nAdded {len(new_instruments)} instrument(s). Total rows: {len(existing_rows)}")
    print("Next: run python scripts/run_pipeline.py")


if __name__ == "__main__":
    main()
