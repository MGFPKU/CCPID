N_COLS = 53  # Total columns in CN regulatory CSV


def make_row(**kwargs) -> list[str]:
    """Build a complete CSV row, filling missing columns with N/A."""
    row = ["N/A"] * N_COLS
    for key, value in kwargs.items():
        if key in HEADER_MAP:
            row[HEADER_MAP[key]] = str(value)
    return row


def insert_instruments(rows: list[list[str]]):
    """Read CN CSV, insert new rows after last PRF, before FRM, write back."""
    with CN_CSV.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.reader(f)
        existing = list(reader)

    # Find insertion point: after last PRF row, before first FRM row
    insert_idx = None
    for i, row in enumerate(existing):
        if i == 0:
            continue
        rid = row[0]
        if rid.startswith("CHNFRM"):
            insert_idx = i
            break

    if insert_idx is None:
        print("ERROR: Could not find FRM row for insertion point")
        sys.exit(1)

    # Insert new rows before FRM
    for j, row in enumerate(rows):
        existing.insert(insert_idx + j, row)

    with CN_CSV.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerows(existing)

    print(f"Inserted {len(rows)} MEA instruments at row {insert_idx}. Total rows: {len(existing)}")
    for i, row in enumerate(rows):
        print(f"  Row {insert_idx + i}: {row[0]} | {row[2][:4]} | {row[6][:50]}")


